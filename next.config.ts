import type { NextConfig } from "next";
import withSerwist from "@serwist/next";

/**
 * ADR-0033 — hard security headers for every route.
 *
 * CSP keeps the app self-contained while allowing the image data: URLs the
 * product/branding pickers produce (img-src data:) and the inline styles/scripts
 * Next.js + Tailwind + framer-motion rely on (style/script 'unsafe-inline').
 * frame-ancestors 'none' + X-Frame-Options DENY block clickjacking.
 */
const securityHeaders = [
  {
    source: "/(.*)",
    headers: [
      {
        key: "Content-Security-Policy",
        value:
          "default-src 'self'; img-src 'self' data: blob:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline'; connect-src 'self'; font-src 'self' data:; frame-ancestors 'none'; base-uri 'self'; form-action 'self'",
      },
      {
        key: "Strict-Transport-Security",
        value: "max-age=31536000; includeSubDomains; preload",
      },
      { key: "X-Frame-Options", value: "DENY" },
      {
        key: "Referrer-Policy",
        value: "strict-origin-when-cross-origin",
      },
      {
        key: "Permissions-Policy",
        value:
          "camera=(), microphone=(), geolocation=(), payment=(), accelerometer=(), gyroscope=()",
      },
      { key: "X-Content-Type-Options", value: "nosniff" },
    ],
  },
];

const nextConfig: NextConfig = {
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return securityHeaders;
  },
};

/**
 * PWA service worker.
 *
 * IMPORTANT — ADR-0008:
 * - Production builds MUST run `next build --webpack`. Turbopack returns exit 0
 *   while emitting NO service worker, which silently removes all offline capability.
 * - `disable` is true outside production so local dev is not misleading; the SW
 *   is generated by the production build and verified by `pwa:guard`.
 */
export default withSerwist({
  swSrc: "src/sw.ts",
  swDest: "public/sw.js",
  disable: process.env.NODE_ENV !== "production",
})(nextConfig);
